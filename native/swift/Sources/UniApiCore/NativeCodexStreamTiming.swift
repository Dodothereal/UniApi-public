import Foundation
import Darwin
import CNativeSystem

/// Internal context travels with the response; the socket owns its observer.
struct NativeCodexStreamTimingContext: Sendable {
    let uptime: @Sendable () -> Double
    let record: @Sendable (NativeCodexStreamTimingObservation) -> Void
    let reasoning: NativeCodexReasoningCounter?
    let requestedModel: String
    init(paths: NativePaths, requestedModel: String, reasoning: NativeCodexReasoningCounter? = nil) {
        uptime = { ProcessInfo.processInfo.systemUptime }
        record = { NativeCodexStreamTimings.record($0, paths: paths) }
        self.reasoning = reasoning
        self.requestedModel = requestedModel
    }
    init(requestedModel: String, uptime: @escaping @Sendable () -> Double, record: @escaping @Sendable (NativeCodexStreamTimingObservation) -> Void, reasoning: NativeCodexReasoningCounter? = nil) {
        self.uptime = uptime; self.record = record; self.reasoning = reasoning; self.requestedModel = requestedModel
    }
}

/// Metadata from the same translated provider request. It is never serialized
/// into the response, so adding observation cannot alter client-visible bytes.
final class NativeCodexReasoningCounter: @unchecked Sendable {
    private let lock = NSLock()
    private var pair: (output: Int, reasoning: Int)?
    func observe(_ usage: JSONValue) {
        guard !usage["completion_tokens"].isNull else { return }
        let output = NativeCodexStreamTimingObserver.integer(usage["completion_tokens"])
        let reasoning = NativeCodexStreamTimingObserver.integer(usage["completion_tokens_details"]["reasoning_tokens"])
        lock.withLock {
            if let output, let reasoning, reasoning <= output { pair = (output, reasoning) }
            else { pair = nil }
        }
    }
    func snapshot() -> (output: Int, reasoning: Int)? { lock.withLock { pair } }
}

/// Metadata captured at host send completion. No response content is persisted.
public struct NativeCodexStreamTimingObservation: Codable, Sendable, Equatable {
    public let responseID: String
    public let model: String
    public let outputTokens: Int
    public let reasoningTokens: Int
    public let streamOutputTokens: Int
    public let durationMs: Double
    public let completedAt: Double
    public let timingSource: String

    var valid: Bool {
        Self.identifier(responseID, limit: 256) && Self.identifier(model, limit: 256) &&
        outputTokens > 0 && outputTokens <= 1_000_000_000 && reasoningTokens >= 0 &&
        reasoningTokens < outputTokens && streamOutputTokens == outputTokens - reasoningTokens &&
        durationMs.isFinite && durationMs > 0 && durationMs <= 86_400_000 &&
        completedAt.isFinite && completedAt > 0 && timingSource == "uniapi-host-sse-clock"
    }
    fileprivate static func identifier(_ value: String, limit: Int) -> Bool {
        !value.isEmpty && !value.contains("://") && value.utf8.count <= limit && value.utf8.allSatisfy {
            (48...57).contains($0) || (65...90).contains($0) || (97...122).contains($0) || [45, 46, 47, 58, 95, 37].contains($0)
        }
    }
}

/// Feed bytes only after host send completion, in send order. This is not a
/// peer receipt clock. A fresh observer belongs to exactly one HTTP Responses
/// request, so tool waits
/// between requests cannot enter its clock. Abort on cancellation or failure.
public struct NativeCodexStreamTimingObserver {
    private let uptime: () -> Double
    private let requestedModel: String
    private var frame = Data(), oversized = false, poisoned = false, terminated = false, dataLines = 0, deliveryTime = 0.0
    private var responseID: String?, first: Double?, last: Double?, deltas = 0
    private var items: [String: (kind: String, bytes: Int)] = [:]
    private var terminal: (id: String, output: Int, reasoning: Int?)?
    private static let frameLimit = 2 * 1024 * 1024

    public init(requestedModel: String, uptime: @escaping () -> Double = { ProcessInfo.processInfo.systemUptime }) { self.requestedModel = requestedModel; self.uptime = uptime }

    public mutating func feedDelivered(_ bytes: Data) {
        feedDelivered(bytes, at: uptime())
    }
    mutating func feedDelivered(_ bytes: Data, at time: Double) {
        deliveryTime = time
        for byte in bytes {
            if byte == 10 {
                if frame.last == 13 { frame.removeLast() }
                if frame.isEmpty { oversized = false; dataLines = 0; continue }
                consumeLine(frame)
                frame.removeAll(keepingCapacity: true)
                oversized = false
            } else if !oversized {
                if frame.count < Self.frameLimit { frame.append(byte) }
                else { frame.removeAll(); oversized = true; poisoned = true }
            }
        }
    }

    // Responses events generated by the shim and native backend carry one
    // complete JSON object on each data line. Multiline data is rejected.
    private mutating func consumeLine(_ line: Data) {
        guard !oversized, line.starts(with: Data("data:".utf8)) else { return }
        dataLines += 1
        guard dataLines == 1 else { poisoned = true; return }
        var payload = Data(line.dropFirst(5)); if payload.first == 32 { payload.removeFirst() }
        if payload == Data("[DONE]".utf8) { if !terminated || terminal == nil { poisoned = true }; return }
        guard !terminated, let value = try? JSONValue.decode(payload), case .object = value else { poisoned = true; return }
        let type = value["type"].string
        switch type {
        case "response.created":
            let id = value["response"]["id"].string
            guard responseID == nil, NativeCodexStreamTimingObservation.identifier(id, limit: 256) else { poisoned = true; return }
            responseID = id
        case "response.output_text.delta", "response.function_call_arguments.delta", "response.custom_tool_call_input.delta":
            guard responseID != nil, case .string(let delta) = value["delta"], !delta.isEmpty else { poisoned = true; return }
            let id = value["item_id"].string
            let kind = type == "response.output_text.delta" ? "message" : type == "response.function_call_arguments.delta" ? "function_call" : "custom_tool_call"
            guard NativeCodexStreamTimingObservation.identifier(id, limit: 256), items.count < 256 || items[id] != nil,
                  items[id] == nil || items[id]?.kind == kind else { poisoned = true; return }
            let now = deliveryTime; guard now.isFinite, now >= 0, last == nil || now >= last! else { poisoned = true; return }
            let old = items[id]?.bytes ?? 0
            guard delta.utf8.count <= 64 * 1024 * 1024 - old else { poisoned = true; return }
            items[id] = (kind, old + delta.utf8.count); if first == nil { first = now }; last = now; deltas += 1
        case "response.completed":
            terminated = true
            let response = value["response"], id = response["id"].string
            let reasonValue = response["usage"]["output_tokens_details"]["reasoning_tokens"]
            let reasoning = Self.integer(reasonValue)
            guard id == responseID, response["status"] == "completed",
                  let output = Self.integer(response["usage"]["output_tokens"]), output > 0,
                  (reasonValue.isNull || reasoning != nil), reasoning == nil || reasoning! < output else { poisoned = true; return }
            guard case .array(let rows) = response["output"], !rows.isEmpty, rows.count <= 256 else { poisoned = true; return }
            var seen = Set<String>()
            for row in rows {
                if row["type"] == "reasoning" { continue }
                let id = row["id"].string, kind = row["type"].string
                guard NativeCodexStreamTimingObservation.identifier(id, limit: 256), seen.insert(id).inserted,
                      let observed = items[id], observed.kind == kind else { poisoned = true; return }
                var count = 0
                if kind == "message" {
                    guard row["role"] == "assistant", case .array(let content) = row["content"], !content.isEmpty else { poisoned = true; return }
                    for part in content {
                        guard part["type"] == "output_text", case .string(let text) = part["text"], text.utf8.count <= 64 * 1024 * 1024 - count else { poisoned = true; return }
                        count += text.utf8.count
                    }
                } else if kind == "function_call", case .string(let arguments) = row["arguments"] { count = arguments.utf8.count }
                else if kind == "custom_tool_call", case .string(let input) = row["input"] { count = input.utf8.count }
                else { poisoned = true; return }
                guard count == observed.bytes else { poisoned = true; return }
            }
            guard !items.isEmpty, seen.count == items.count else { poisoned = true; return }
            terminal = (id, output, reasoning)
        case "response.failed", "response.incomplete", "error": poisoned = true; terminated = true
        default: break
        }
    }
    fileprivate static func integer(_ value: JSONValue) -> Int? {
        guard case .number(let n) = value, n.isFinite, n >= 0, n <= 1_000_000_000, n.rounded(.towardZero) == n else { return nil }
        return Int(n)
    }
    public func finish(success: Bool, completedAt: Double = Date().timeIntervalSince1970) -> NativeCodexStreamTimingObservation? {
        finish(success: success, completedAt: completedAt, providerReasoning: nil)
    }
    func finish(success: Bool, completedAt: Double = Date().timeIntervalSince1970, providerReasoning: (output: Int, reasoning: Int)?) -> NativeCodexStreamTimingObservation? {
        guard success, !poisoned, frame.isEmpty, !oversized, deltas >= 2,
              let first, let last, let terminal else { return nil }
        let reasoning = terminal.reasoning ?? (providerReasoning?.output == terminal.output ? providerReasoning?.reasoning : nil)
        guard let reasoning, reasoning >= 0, reasoning < terminal.output else { return nil }
        let result = NativeCodexStreamTimingObservation(responseID: terminal.id, model: requestedModel, outputTokens: terminal.output,
            reasoningTokens: reasoning, streamOutputTokens: terminal.output - reasoning,
            durationMs: (last - first) * 1000, completedAt: completedAt, timingSource: "uniapi-host-sse-clock")
        return result.valid ? result : nil
    }
}

/// Bounded, owner-only storage. A reader never follows links or trusts malformed
/// rows. Writers serialize with an advisory lock and discard old rows on rotation.
public enum NativeCodexStreamTimings {
    public enum SnapshotError: Error, Equatable { case busy, unavailable }
    private enum DirectoryError: Error { case missing }
    private static let name = "stream-timings.jsonl", maximum = 1024 * 1024, rowLimit = 4096
    private static let queue = DispatchQueue(label: "uniapi.statistics.stream-timings")
    private static let queueLock = NSLock()
    private static var pending = 0

    /// Schedules best-effort storage away from inference. Failure is intentionally silent.
    public static func record(_ observation: NativeCodexStreamTimingObservation, paths: NativePaths) {
        guard !paths.readOnly, observation.valid else { return }
        let admitted = queueLock.withLock { () -> Bool in
            guard pending < 128 else { return false }
            pending += 1; return true
        }
        guard admitted else { return }
        queue.async {
            defer { queueLock.withLock { pending -= 1 } }
            try? append(observation, paths: paths)
        }
    }
    public static func read(paths: NativePaths) -> [String: NativeCodexStreamTimingObservation] {
        (try? readSnapshot(paths: paths)) ?? [:]
    }
    /// A missing journal is empty; contention, unsafe paths, malformed records,
    /// and I/O failures are failures so callers can retry the same signature.
    public static func readSnapshot(paths: NativePaths) throws -> [String: NativeCodexStreamTimingObservation] {
        let folder: Int32
        do { folder = try directory(paths: paths, create: false) }
        catch DirectoryError.missing { return [:] }
        catch { throw SnapshotError.unavailable }
        defer { close(folder) }
        let fd = openat(folder, name, O_RDONLY | O_NOFOLLOW | O_NONBLOCK | O_CLOEXEC)
        if fd < 0 { if errno == ENOENT { return [:] }; throw SnapshotError.unavailable }
        defer { close(fd) }
        guard safeFile(fd) else { throw SnapshotError.unavailable }
        if flock(fd, LOCK_SH | LOCK_NB) != 0 {
            if errno == EWOULDBLOCK || errno == EAGAIN { throw SnapshotError.busy }
            throw SnapshotError.unavailable
        }
        defer { flock(fd, LOCK_UN) }
        var info = stat(); guard fstat(fd, &info) == 0, info.st_size >= 0, info.st_size <= Int64(maximum) else { throw SnapshotError.unavailable }
        var data = Data(count: Int(info.st_size))
        var offset = 0
        while offset < data.count {
            let count = data.withUnsafeMutableBytes { Darwin.read(fd, $0.baseAddress!.advanced(by: offset), $0.count - offset) }
            if count < 0 && errno == EINTR { continue }
            guard count > 0 else { throw SnapshotError.unavailable }
            offset += count
        }
        guard data.isEmpty || data.last == 10 else { throw SnapshotError.unavailable }
        var result: [String: NativeCodexStreamTimingObservation] = [:]
        for line in data.split(separator: 10, omittingEmptySubsequences: true).suffix(4096) {
            guard line.count <= rowLimit, let row = try? JSONDecoder().decode(NativeCodexStreamTimingObservation.self, from: Data(line)), row.valid else { throw SnapshotError.unavailable }
            result["codex:" + row.responseID] = row
        }
        return result
    }
    static func append(_ row: NativeCodexStreamTimingObservation, paths: NativePaths) throws {
        let folder = try directory(paths: paths, create: true); defer { close(folder) }
        let fd = openat(folder, name, O_RDWR | O_APPEND | O_CREAT | O_NOFOLLOW | O_NONBLOCK | O_CLOEXEC, 0o600)
        guard fd >= 0 else { throw NativeFailure("Timing journal unavailable") }; defer { close(fd) }
        guard safeFile(fd), flock(fd, LOCK_EX | LOCK_NB) == 0 else { throw NativeFailure("Timing journal unsafe or busy") }; defer { flock(fd, LOCK_UN) }
        let bytes = try JSONEncoder().encode(row) + Data([10])
        guard bytes.count <= rowLimit else { throw NativeFailure("Timing record too large") }
        var info = stat(); guard fstat(fd, &info) == 0, info.st_size >= 0, info.st_size <= Int64(maximum) else { throw NativeFailure("Timing journal too large") }
        if info.st_size + Int64(bytes.count) > Int64(maximum) { guard ftruncate(fd, 0) == 0 else { throw NativeFailure("Timing rotation failed") } }
        let written = bytes.withUnsafeBytes { Darwin.write(fd, $0.baseAddress, $0.count) }
        guard written == bytes.count else { throw NativeFailure("Timing record write failed") }
    }
    private static func safeFile(_ fd: Int32) -> Bool {
        var info = stat()
        guard fstat(fd, &info) == 0 && info.st_mode & S_IFMT == S_IFREG && info.st_nlink == 1 && info.st_uid == geteuid() && info.st_mode & 0o7777 == 0o600 else { return false }
        errno = 0
        let acl = acl_get_fd_np(fd, ACL_TYPE_EXTENDED), code = errno
        if let acl { acl_free(UnsafeMutableRawPointer(acl)) }
        return acl == nil && code == ENOENT
    }
    private static func directory(paths: NativePaths, create: Bool) throws -> Int32 {
        var path = paths.data.standardizedFileURL.path
        for alias in ["/var", "/tmp", "/etc"] where path == alias || path.hasPrefix(alias + "/") { path = "/private" + path; break }
        var fd = open("/", O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard fd >= 0 else { throw NativeFailure("Timing directory unavailable") }
        for component in path.split(separator: "/") {
            let next = openat(fd, String(component), O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
            let code = errno; close(fd)
            if next < 0 { if code == ENOENT && !create { throw DirectoryError.missing }; throw NativeFailure("Timing directory unsafe") }; fd = next
            var info = stat()
            guard fstat(fd, &info) == 0, info.st_uid == 0 || info.st_uid == geteuid() else { close(fd); throw NativeFailure("Timing directory owner invalid") }
        }
        var dataInfo = stat()
        guard fstat(fd, &dataInfo) == 0, dataInfo.st_uid == geteuid() else { close(fd); throw NativeFailure("Timing data owner invalid") }
        if create && mkdirat(fd, "statistics", 0o700) != 0 && errno != EEXIST { close(fd); throw NativeFailure("Timing directory unavailable") }
        let next = openat(fd, "statistics", O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC), openCode = errno; close(fd)
        if next < 0 { if openCode == ENOENT && !create { throw DirectoryError.missing }; throw NativeFailure("Timing directory unsafe") }
        var info = stat()
        guard fstat(next, &info) == 0, info.st_uid == geteuid(), info.st_mode & 0o7777 == 0o700 else { close(next); throw NativeFailure("Timing directory permissions invalid") }
        errno = 0
        let acl = acl_get_fd_np(next, ACL_TYPE_EXTENDED), code = errno
        if let acl { acl_free(UnsafeMutableRawPointer(acl)) }
        guard acl == nil && code == ENOENT else { close(next); throw NativeFailure("Timing directory access controls invalid") }
        return next
    }
}
