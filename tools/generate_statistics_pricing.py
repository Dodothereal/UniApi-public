#!/usr/bin/env python3
"""Validate the shared price ledger and embed it in the native executable."""
import argparse
import datetime
import json
import math
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "resources/pricing-catalog.json"
OUTPUT = ROOT / "native/swift/Sources/UniApiCore/StatisticsPriceCatalog.swift"
COMPONENTS = {"input", "output", "cacheWrite", "cacheRead"}


def validate(catalog):
    def text_field(value):
        return isinstance(value, str) and bool(value.strip())

    def identity(value):
        return text_field(value) and value == value.strip().lower()

    assert isinstance(catalog, dict)
    assert type(catalog["schema"]) is int and catalog["schema"] == 1 and catalog["currency"] == "USD"
    assert text_field(catalog["checkedAt"]) and text_field(catalog["basis"])
    assert datetime.date.fromisoformat(catalog["checkedAt"]).isoformat() == catalog["checkedAt"]
    assert isinstance(catalog["models"], list) and catalog["models"], "A release catalog must contain verified prices."
    assert isinstance(catalog["unpriced"], list)
    names = set()
    for model in catalog["models"]:
        assert isinstance(model, dict) and identity(model["id"])
        assert all(text_field(model[field]) for field in ("name", "vendor", "assumption", "sourceURL"))
        assert model["checkedAt"] == catalog["checkedAt"]
        assert isinstance(model["aliases"], list) and all(identity(name) for name in model["aliases"])
        url = urlsplit(model["sourceURL"])
        assert url.scheme == "https" and url.hostname and not url.username and not url.password
        assert isinstance(model["rates"], dict) and set(model["rates"]) == COMPONENTS
        for value in model["rates"].values():
            assert value is None or (type(value) in (int, float) and math.isfinite(value) and value >= 0)
        assert any(value is not None for value in model["rates"].values())
        for name in [model["id"], *model["aliases"]]:
            assert name not in names, name
            names.add(name)
    unknown = set()
    for model in catalog["unpriced"]:
        assert isinstance(model, dict) and identity(model["id"]) and text_field(model["reason"])
        assert model["id"] not in names and model["id"] not in unknown
        unknown.add(model["id"])
    text = json.dumps(catalog, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    assert '"""#####' not in text and "\\#####(" not in text
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = validate(json.loads(CATALOG.read_text()))
    generated = (
        "// Generated by tools/generate_statistics_pricing.py; edit pricing-catalog.json.\n"
        "// Embedded data avoids filesystem or network work when Statistics opens.\n"
        "enum StatisticsPriceCatalog {\n"
        "    static let json = #####\"\"\"\n" + text + "\n\"\"\"#####\n}\n"
    )
    if args.check:
        assert OUTPUT.read_text() == generated, "Native pricing catalog is stale; regenerate it."
    else:
        OUTPUT.write_text(generated)
    print("Statistics price catalog validated" + (" and source matches." if args.check else " and generated."))


if __name__ == "__main__":
    main()
